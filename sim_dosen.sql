
-- =========================================
-- Database Schema: sim_dosen
-- Database: PostgreSQL (Neon)
-- =========================================

BEGIN;

-- =========================================
-- Table: dosen
-- =========================================

CREATE TABLE IF NOT EXISTS dosen (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nomor_registrasi VARCHAR(50),
    nuptk VARCHAR(30),
    nama VARCHAR(150) NOT NULL,
    nip VARCHAR(30),

    jabatan_fungsional VARCHAR(100),
    kepangkatan VARCHAR(100),
    pendidikan_terakhir VARCHAR(100),
    rumpun_ilmu VARCHAR(150),

    status_serdos VARCHAR(50),
    status_pegawai VARCHAR(50),
    ikatan_kerja VARCHAR(100),
    status_aktivitas VARCHAR(50),
    penempatan VARCHAR(150),

    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- =========================================
-- Function: Update updated_at automatically
-- =========================================

CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- =========================================
-- Trigger: dosen updated_at
-- =========================================

DROP TRIGGER IF EXISTS trigger_dosen_updated_at ON dosen;

CREATE TRIGGER trigger_dosen_updated_at
BEFORE UPDATE ON dosen
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

COMMIT;
